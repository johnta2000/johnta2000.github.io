// Package the standalone schedule's markup/styles for same-document use in Rally.
// There is one shared controller; this generated asset contains no second runtime.
import {readFile,writeFile} from 'node:fs/promises';
const base=new URL('../',import.meta.url);
const html=await readFile(new URL('lost-lands-2026-lineup/index.html',base),'utf8');
const mobile=await readFile(new URL('lost-lands-2026-lineup/mobile.css',base),'utf8');
const markup=html.split('<body>')[1].split('<script')[0].trim();
const css=([...html.matchAll(/<style>([\s\S]*?)<\/style>/g)].map(match=>match[1]).join('\n')+'\n'+mobile)
  .replace(/:root/g,':host')
  .replace(/(?<![-\w])(?:html|body)(?![-\w])/g,':host')
  .replace(/\.rally-mode/g,':host(.rally-mode)')
  .replaceAll('./assets/','/lost-lands-2026-lineup/assets/');
const finalCss=css+'\n:host{display:block;min-height:0;height:100%;overflow:auto;overscroll-behavior-y:contain;background:#f5f4ed;color:#252820;color-scheme:light;font-size:16px;}\n:host::before,:host::after{display:none} [hidden]{display:none!important}';
await writeFile(new URL('tools/rally/lineup-template.js',base),'// Generated by scripts/build-native-lineup.mjs. Do not edit.\nwindow.RallyLineupTemplate='+JSON.stringify({markup,css:finalCss})+';\n');
console.log('Native lineup template built from the shared schedule.');
